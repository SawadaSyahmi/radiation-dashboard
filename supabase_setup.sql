-- Radiation Dashboard Supabase setup

create table if not exists public.radiation_readings
(
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    device_id text not null,
    dose_rate double precision,
    dose double precision,
    cps integer,
    cpm integer,
    average double precision,
    detector_time bigint,
    detector_s double precision,
    warning integer
);

alter table public.radiation_readings
enable row level security;

grant select, insert
on table public.radiation_readings
to anon;

-- Create only if equivalent policies do not already exist:
create policy "Public dashboard read"
on public.radiation_readings
for select
to anon
using (true);

create policy "FS5000 device insert"
on public.radiation_readings
for insert
to anon
with check (device_id = 'FS5000-01');
